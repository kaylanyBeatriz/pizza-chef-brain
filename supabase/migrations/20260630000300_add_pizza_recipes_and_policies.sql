create table if not exists public.pizza_ingredients (
  id bigint generated by default as identity primary key,
  pizza_id integer not null references public.pizzas(id) on delete cascade,
  ingredient_id integer not null references public.ingredients(id) on delete restrict,
  quantity numeric(12, 3) not null check (quantity > 0),
  created_at timestamptz not null default now(),
  unique (pizza_id, ingredient_id)
);

alter table public.pizzas enable row level security;
alter table public.pizza_ingredients enable row level security;

drop policy if exists "pizzas_select_authenticated" on public.pizzas;
create policy "pizzas_select_authenticated"
on public.pizzas for select to authenticated
using (exists (
  select 1 from public.users where users.id = auth.uid()
));

drop policy if exists "pizzas_insert_admin_manager" on public.pizzas;
create policy "pizzas_insert_admin_manager"
on public.pizzas for insert to authenticated
with check (exists (
  select 1 from public.users
  where users.id = auth.uid()
    and users.role in ('admin', 'gerente')
));

drop policy if exists "pizzas_update_admin_manager" on public.pizzas;
create policy "pizzas_update_admin_manager"
on public.pizzas for update to authenticated
using (exists (
  select 1 from public.users
  where users.id = auth.uid()
    and users.role in ('admin', 'gerente')
))
with check (exists (
  select 1 from public.users
  where users.id = auth.uid()
    and users.role in ('admin', 'gerente')
));

drop policy if exists "pizzas_delete_admin_manager" on public.pizzas;
create policy "pizzas_delete_admin_manager"
on public.pizzas for delete to authenticated
using (exists (
